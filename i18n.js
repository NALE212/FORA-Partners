  if (note) {
    let seen = false;
    try { seen = localStorage.getItem("cookie-notice") === "1"; } catch (e) {}
    note.hidden = seen;
    document.getElementById("cookie-ok").addEventListener("click", () => {
      note.hidden = true;
      try { localStorage.setItem("cookie-notice", "1"); } catch (e) {}
    });
  }
