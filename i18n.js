    lang = LANGS.includes(l) ? l : "en";
    document.documentElement.lang = lang;
    document.title = t(titleEn);
    textNodes.forEach(x => { if (x.n.parentElement && x.n.parentElement.id !== "details-label") x.n.nodeValue = x.lead + t(x.en) + x.trail; });
