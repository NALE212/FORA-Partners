  const roleCopy = { supplier: "What do you offer?", buyer: "What are you looking for?" };
  let role = "supplier";
  const detailsLabel = document.getElementById("details-label");
  function renderRole() { if (detailsLabel) detailsLabel.textContent = t(roleCopy[role]); }
